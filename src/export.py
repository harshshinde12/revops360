"""Board-ready export: markdown summary + filtered CSV helper."""
from __future__ import annotations

import pandas as pd


def board_summary_md(month: str, kpis: dict, coverage: pd.DataFrame,
                     fva: pd.DataFrame, alert_list: list[str],
                     scenarios: pd.DataFrame) -> str:
    lines = [
        f"# RevOps360 — Board Summary ({month})",
        "",
        "## KPIs (all time)",
        f"- Opportunities: {kpis.get('opps', 0):,}",
        f"- Win rate: {float(kpis.get('win_rate', 0)):.1%}",
        f"- Avg deal (won): ${float(kpis.get('avg_deal', 0)):,.0f}",
        f"- Median cycle: {kpis.get('median_cycle', 0)} days",
        f"- Won revenue: ${float(kpis.get('won_revenue', 0)):,.0f}",
        f"- Weighted open pipeline: ${float(kpis.get('weighted_pipeline', 0)):,.0f}",
        "",
        "## Coverage by region",
    ]
    for _, r in coverage.iterrows():
        lines.append(
            f"- {r['region']}: coverage {r['coverage']}x "
            f"(won ${r['won_revenue']:,.0f} / open-exp ${r['open_expected']:,.0f} "
            f"/ target ${r['target']:,.0f})"
        )
    lines += ["", "## Forecast scenarios (target month)", ""]
    for _, r in scenarios.iterrows():
        lines.append(f"- {r['scenario']}: ${r['forecast']:,.0f} (x{r['multiplier']})")
    lines += ["", "## Forecast vs actual (last months)", ""]
    for _, r in fva.tail(6).iterrows():
        lines.append(
            f"- {r['month']}: predicted ${r['predicted_trend']:,.0f} vs "
            f"actual ${r['actual']:,.0f} (var {r['variance_pct']:.1%})"
        )
    lines += ["", "## Alerts", ""]
    lines += [f"- {a}" for a in alert_list]
    lines += ["", "_Generated by RevOps360. Methodology: docs/kpi_dictionary.md_"]
    return "\n".join(lines) + "\n"
